"""Config loading for the browserless proxy.

weavy_config.json shape (generated by generate_weavy_config.py):
{
  "cookie_header": "cf_clearance=...; __cf_bm=...; ...",   // raw Cookie header from a captured request
  "user_agent": "Mozilla/5.0 ... Chrome/154...",            // UA of the browser that issued those cookies
  "refresh_token": "AMf-vBx...",                            // Firebase refresh token (long-lived, rolling)
  "firebase_api_key": "AIza...",                            // public Firebase web key (auto-extracted when possible)
  "proxy_key": null,                                        // optional: require Authorization: Bearer <key> on the local API
  "port": 8787
}
"""

from __future__ import annotations

import json
import os
from pathlib import Path

CONFIG_PATH = os.environ.get("WEAVY_CONFIG", "weavy_config.json")


def load_config(path: str | Path = CONFIG_PATH) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        cfg = json.load(f)
    for field in ("cookie_header", "user_agent", "refresh_token"):
        if not cfg.get(field):
            raise SystemExit(f"weavy_config.json is missing required field: {field}")
    return cfg
